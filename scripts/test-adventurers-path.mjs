import assert from "node:assert/strict";
import { createRequire } from "node:module";
const require=createRequire(import.meta.url),Path=require("../adventurers-path.js"),day="2026-11-10";
const guild={ensure(s){return s.guild||(s.guild={daily:{claimed:[],contracts:[{id:"kills",target:5,type:"kills"},{id:"crafts",target:3,type:"crafts"}]}})},progress(s,p,c){return c.type==="kills"?s.guildStats?.kills||0:s.guildStats?.crafts||0}};
const player={xp:200,gear:{weapon:"sword",armor:"shield",companion:"pet"},descent:{depth:2},guildStats:{kills:2,crafts:1},stepsToday:2500,stepLifetime:10000};
let html=Path.render(player,day,400,2,guild);
assert.match(html,/THE ADVENTURER’S PATH/);
assert.match(html,/GUILD COMMISSIONS/);
assert.match(html,/HUNT THE DEPTHS/);
assert.match(html,/2 MONSTERS DEFEATED/);
assert.match(html,/MASTER THE WORKBENCH/);
assert.match(html,/1 ITEMS CRAFTED/);
assert.match(html,/3 \/ 3 SLOTS EQUIPPED/);
assert.doesNotMatch(html,/STEPS|STRIDE|WALKING/i,"The Path must not use step-based objectives");
player.guildStats.kills=10;player.guildStats.crafts=5;player.guild.daily.claimed=["one","two","three"];html=Path.render(player,day,400,2,guild);
assert.match(html,/4 \/ 4/);
assert.match(html,/is-complete/);
assert.equal(player.stepsToday,2500,"Rendering must not mutate historic step records");
console.log("Adventurer's Path activity tests passed.");
