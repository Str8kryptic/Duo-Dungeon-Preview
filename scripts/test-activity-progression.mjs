import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { runInNewContext } from "node:vm";
const window={DUO_DATA:{shopItems:[{id:"test-sword",set:"test",effects:{coins:0.2,xp:0.1}},{id:"test-armor",set:"test",effects:{coins:0.05}}],relicCatalog:[]},setInterval(){return 1},clearInterval(){}};
runInNewContext(readFileSync(new URL("../rpg-combat.js",import.meta.url),"utf8"),{window,Date,Math});
const Combat=window.DUO_RPG_COMBAT;
assert.ok(Combat,"Hunt module should expose its API");
const state={coins:100,xp:0,gear:{weapon:"test-sword",armor:"test-armor"},upgrades:{"test-sword":2},guildStats:{kills:0,crafts:0},monsterKills:{},monsterKillTotal:0,activePotions:[{endsAt:Date.now()+60000,effect:{coins:0.5,xp:0.5}}]};
const hooks={save(){},render(){},toast(){},notify(){}};
Combat.ensure(state);
Combat.handleAction(state,"hunt:cave-stalker",hooks);
assert.ok(state.rpgCombat.battle,"Hunt should start a battle");
state.rpgCombat.battle.hp=1;
Combat.handleAction(state,"quick-strike",hooks);
assert.equal(state.guildStats.kills,1,"Hunt victory should advance Guild kill progress");
assert.equal(state.monsterKillTotal,1,"Hunt victory should update the lifetime elimination ledger");
assert.ok(state.xp>28,"Hunt victory should award boosted global XP");
assert.ok(state.coins>142,"Hunt victory should award boosted coins");
state.rpgCombat.inventory.materials.bitter_herb=2;
state.rpgCombat.inventory.materials.venom_gland=1;
Combat.handleAction(state,"craft-healing",hooks);
assert.equal(state.guildStats.crafts,1,"Alchemy crafting should advance Guild craft progress");
assert.equal(state.rpgCombat.inventory.potions,1,"Crafting should still grant the consumable");
console.log("Hunt activity reward tests passed.");
